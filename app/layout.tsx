import type { Metadata, Viewport } from "next";
import { Analytics } from "@vercel/analytics/next";
import localFont from "next/font/local";
import { weddingConfig } from "@/config/weddingConfig";
import "./globals.css";

// ── Fonts ─────────────────────────────────────────────────────
//  Self-hosted from /app/fonts (Google Fonts latin subsets, OFL licensed).
//  next/font inlines @font-face + preloads → no flash of unstyled text and
//  no third-party request at runtime. Variable files cover all weights.
const cormorant = localFont({
  src: [
    { path: "./fonts/cormorant-garamond-normal.woff2", weight: "300 700", style: "normal" },
    { path: "./fonts/cormorant-garamond-italic.woff2", weight: "300 700", style: "italic" },
  ],
  variable: "--font-cormorant",
  display: "swap",
});
const playfair = localFont({
  src: [
    { path: "./fonts/playfair-display-normal.woff2", weight: "400 900", style: "normal" },
    { path: "./fonts/playfair-display-italic.woff2", weight: "400 900", style: "italic" },
  ],
  variable: "--font-playfair",
  display: "swap",
});
const poppins = localFont({
  src: [
    { path: "./fonts/poppins-300.woff2", weight: "300", style: "normal" },
    { path: "./fonts/poppins-400.woff2", weight: "400", style: "normal" },
    { path: "./fonts/poppins-500.woff2", weight: "500", style: "normal" },
    { path: "./fonts/poppins-600.woff2", weight: "600", style: "normal" },
  ],
  variable: "--font-poppins",
  display: "swap",
});
const greatVibes = localFont({
  src: [{ path: "./fonts/great-vibes-400.woff2", weight: "400", style: "normal" }],
  variable: "--font-great-vibes",
  display: "swap",
});

const { bride, groom, weddingDateDisplay } = weddingConfig;
const title = `${bride.firstName} & ${groom.firstName} — Wedding Invitation | ${weddingDateDisplay}`;
const shortTitle = `${bride.firstName} & ${groom.firstName} — Wedding Invitation`;
const description = `You are cordially invited to the wedding of ${bride.fullName} and ${groom.fullName} on ${weddingDateDisplay}. Two hearts, one beautiful journey.`;

/**
 * Absolute base used to resolve the OG/Twitter image URLs in share previews.
 * Set NEXT_PUBLIC_SITE_URL in your hosting env (e.g. https://mansi-tanuj.vercel.app);
 * falls back to the Vercel-provided URL, then localhost for dev.
 */
const siteUrl =
  process.env.NEXT_PUBLIC_SITE_URL ??
  (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : undefined) ??
  (process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : "http://localhost:3000");

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title,
  description,
  keywords: ["wedding", "invitation", bride.fullName, groom.fullName, weddingDateDisplay],
  openGraph: {
    title: shortTitle,
    description: `Join us to celebrate our wedding on ${weddingDateDisplay}`,
    type: "website",
    // Image is generated by app/opengraph-image.tsx
  },
  twitter: {
    card: "summary_large_image",
    title: shortTitle,
    description: `Join us to celebrate our wedding on ${weddingDateDisplay}`,
  },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  themeColor: "#4A0A12",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" className={`${cormorant.variable} ${playfair.variable} ${poppins.variable} ${greatVibes.variable}`}>
      <body className="bg-cream font-poppins antialiased">
        {children}
        <Analytics />
      </body>
    </html>
  );
}
